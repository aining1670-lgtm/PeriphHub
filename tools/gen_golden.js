// Dump golden data from the community web driver into golden/*.json and the
// C++ key table. Run with node; the web driver sources are not vendored here.
//
//   1. fetch https://<web-driver-host>/js/define-v100.js  -> build/define-v100.js
//   2. node tools/gen_golden.js
//
// Output:
//   golden/keys.json          108 x {code, label, usage}
//   native/src/keytable.inc   the same table for protocol.cpp (generated)
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const build = path.join(root, 'build');
const golden = path.join(root, 'golden');

function readIfExists(file) {
  // build/ is the working copy; golden/ keeps the vendored snapshot so a fresh
  // clone can regenerate the table without network access.
  for (const dir of [build, golden]) {
    const full = path.join(dir, file);
    if (fs.existsSync(full)) return fs.readFileSync(full, 'utf8');
  }
  return null;
}

function extractKeyTable(source) {
  // The driver assigns one row at a time:
  //   vkPOS[i++]=["KeyA", "A", 0x04];   // [KeyboardEvent.code, label, HID usage]
  // 108 rows: keyboard HID page plus mouse usages 0xF0..0xF2.
  const entries = [];
  for (const row of source.matchAll(
    /vkPOS\[i\+\+\]\s*=\s*\[\s*"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*(0x[0-9a-fA-F]+)\s*\]/g
  )) {
    entries.push({ code: row[1], label: row[2], usage: parseInt(row[3], 16) });
  }
  return entries;
}

function cppString(text) {
  return '"' + text.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

function writeKeyTableInc(keys) {
  const lines = [
    '// Generated by tools/gen_golden.js from build/define-v100.js. Do not edit.',
    '// KeyboardEvent.code -> display label -> HID usage (mouse buttons 0xF0..0xF2).',
    'static const KeyNameEntry kKeyNames[] = {',
  ];
  for (const key of keys) {
    lines.push(
      `    {${cppString(key.code)}, ${cppString(key.label)}, 0x${key.usage.toString(16).padStart(2, '0')}},`
    );
  }
  lines.push('};', 'static const int kKeyNameCount = ' + keys.length + ';', '');
  fs.writeFileSync(path.join(root, 'native', 'src', 'keytable.inc'), lines.join('\n'));
}

function main() {
  fs.mkdirSync(golden, { recursive: true });
  const defineSource = readIfExists('define-v100.js');
  if (!defineSource) {
    console.log('build/define-v100.js missing — see the header of this file.');
    return;
  }
  const keys = extractKeyTable(defineSource);
  if (keys.length !== 108) throw new Error(`expected 108 keys, got ${keys.length}`);
  fs.writeFileSync(path.join(golden, 'keys.json'), JSON.stringify(keys, null, 2));
  writeKeyTableInc(keys);
  console.log(`golden/keys.json: ${keys.length} keys`);
  console.log('native/src/keytable.inc: written');
}

main();
